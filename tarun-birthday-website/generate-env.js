/**
 * Generates env.js from .env or system environment variables.
 * Usage: node generate-env.js
 * Useful for Netlify, Vercel, GitHub Actions or local automated builds.
 */
const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '.env');
const outPath = path.join(__dirname, 'env.js');

let scriptUrl = process.env.GOOGLE_APPS_SCRIPT_URL || '';
let sharedSecret = process.env.SHARED_SECRET || 'CHANGE_THIS_TO_A_LONG_RANDOM_SECRET';

// If .env exists, read and override
if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf8');
  content.split('\n').forEach(line => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (key === 'GOOGLE_APPS_SCRIPT_URL' && val) scriptUrl = val;
      if (key === 'SHARED_SECRET' && val) sharedSecret = val;
    }
  });
}

const fileContent = `// Environment Variables for The Tarun Times
// Auto-generated by generate-env.js
window.__ENV__ = {
  GOOGLE_APPS_SCRIPT_URL: ${JSON.stringify(scriptUrl)},
  SHARED_SECRET: ${JSON.stringify(sharedSecret)}
};
`;

fs.writeFileSync(outPath, fileContent, 'utf8');
console.log('Successfully generated env.js from environment configuration.');
